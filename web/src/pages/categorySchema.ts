export function specOf(category: string): CategorySpec {
    const d = DEFS[category] ?? DEFS.generic!;
    const c = DEFS[category] ? category : 'generic';
    const has = d.mode !== 'hidden';
    return {
        address: d.mode, kinds: d.kinds,
        addressLabel: has ? textUI(k(`m_cf_${c}_addr_l`)) : '', addressPlaceholder: has ? textUI(k(`m_cf_${c}_addr_p`)) : '', addressHint: has ? textUI(k(`m_cf_${c}_addr_h`)) : '',
        platform: d.platform, arch: d.arch, internet: d.internet, testable: d.testable,
        fields: d.fields.map((f) => ({ key: f.key, kind: f.kind, required: f.required, label: textUI(k(`m_cf_${c}_${f.key}`)), placeholder: f.kind === 'text' ? textUI(k(`m_cf_${c}_${f.key}_p`)) : '', options: f.options.map(opt) })),
    };
}
export const kindsText = (kinds: string[]) => kinds.map(KIND_LABEL).join(', ');
// Alamat per baris -> baris pertama yang tidak cocok dengan jenis yang diterima kategori (server tetap memvalidasi).
export function badAddress(lines: string[], kinds: string[], infer: (v: string) => string): string | null {
    for (const line of lines) {
        const kind = infer(line);
        const ok = kinds.includes(kind) || (kind === 'domain' && kinds.includes('hostname')) || (kind === 'hostname' && kinds.includes('domain'));
        if (!ok) return line;
    }
    return null;
}
export function scannable(addresses: { kind: string; scan_approved?: boolean }[]): boolean {
    return addresses.some((a) => SCANNABLE_KINDS.includes(a.kind));
}

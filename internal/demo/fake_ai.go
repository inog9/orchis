const fakeAPIKey = "demo-local-fake-only"

// A second boundary independent of Provider.TestURL: demo seeding cannot dial any
// origin except the ephemeral loopback listener it created itself.
type ownedOrigin struct {
	origin string
	next   http.RoundTripper
}

func (o ownedOrigin) RoundTrip(r *http.Request) (*http.Response, error) {
	if r.URL.Scheme != "http" || r.URL.Host != o.origin {
		return nil, errors.New("demo provider origin refused")
	}
	return o.next.RoundTrip(r)
}

func newLocalFakeAI() (*ai.Provider, func(), error) {
	listener, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		return nil, nil, err
	}
	server := &http.Server{ReadHeaderTimeout: 2 * time.Second, ReadTimeout: 5 * time.Second, WriteTimeout: 5 * time.Second, Handler: http.HandlerFunc(fakeAIResponse)}
	go func() { _ = server.Serve(listener) }()
	p, err := ai.NewProvider("", "http://"+listener.Addr().String())
	if err != nil {
		server.Close()
		return nil, nil, err
	}
	transport := p.Client.Transport
	p.Client.Transport = ownedOrigin{listener.Addr().String(), transport}
	close := func() {
		if t, ok := transport.(*http.Transport); ok {
			t.CloseIdleConnections()
		}
		_ = server.Close()
	}
	return p, close, nil
}

func fakeAIResponse(w http.ResponseWriter, r *http.Request) {
	if r.Method != "POST" || r.Header.Get("Authorization") != "Bearer "+fakeAPIKey {
		http.Error(w, "invalid local fixture request", 400)
		return
	}
	body, err := io.ReadAll(io.LimitReader(r.Body, 128*1024+1))
	if err != nil || len(body) > 128*1024 {
		http.Error(w, "fixture request too large", 413)
		return
	}
	var request struct {
		Model    string                           `json:"model"`
		Input    string                           `json:"input"`
		Messages []struct{ Role, Content string } `json:"messages"`
	}
	if json.Unmarshal(body, &request) != nil || !strings.HasPrefix(request.Model, "demo-") {
		http.Error(w, "synthetic model required", 400)
		return
	}
	input := request.Input
	if r.URL.Path == "/chat/completions" {
		for _, m := range request.Messages {
			if m.Role == "user" {
				input = m.Content
			}
		}
	} else if r.URL.Path != "/v1/responses" {
		http.NotFound(w, r)
		return
	}
	var in ai.Input
	if json.Unmarshal([]byte(input), &in) != nil {
		http.Error(w, "invalid fixture input", 400)
		return
	}
	out := ai.Output{Summary: "DEMO / SYNTHETIC - generated by an owned local fake API. No external AI model or scan was invoked.", Remediations: []ai.Advice{}, Actions: []ai.Action{}}
	for _, asset := range in.Assets {
		for _, finding := range asset.Findings {
			out.Remediations = append(out.Remediations, ai.Advice{FindingID: finding.ID, Recommendation: "Demo/synthetic placeholder: verify the actual evidence before making a change.", Validation: "Synthetic example only. Validate against an authorized local assessment."})
		}
	}
	if r.URL.Path == "/chat/completions" && len(in.Assets) > 0 {
		out.Actions = append(out.Actions, ai.Action{AssetID: in.Assets[0].ID, ContractKey: "nmap.tcp_connect", Version: 1, Params: json.RawMessage(`{"profile":"web","service_detection":false}`), Reason: "Demo/synthetic proposed check for review only. Never dispatch this fixture."})
	}
	raw, _ := json.Marshal(out)
	w.Header().Set("Content-Type", "application/json")
	if r.URL.Path == "/chat/completions" {
		_ = json.NewEncoder(w).Encode(map[string]any{"choices": []any{map[string]any{"finish_reason": "stop", "message": map[string]any{"content": string(raw)}}}, "usage": map[string]any{"total_tokens": 32}})
	} else {
		_ = json.NewEncoder(w).Encode(map[string]any{"status": "completed", "output": []any{map[string]any{"type": "message", "content": []any{map[string]any{"type": "output_text", "text": string(raw)}}}}, "usage": map[string]any{"total_tokens": 32}})
	}
}

func localFakeOutput(ctx context.Context, p *ai.Provider, claim ai.Claim) (ai.Output, int, error) {
	raw, usage, err := p.Generate(ctx, claim)
	if err != nil {
		return ai.Output{}, 0, err
	}
	out, err := ai.ValidateOutput(raw, claim.Job.Input, claim.Job.Kind)
	return out, usage, err
}
